"""SYNTHETIC usage history for the forecast engine, derived from made-up dish sales x recipes.

    py -3 -m backend.inventory.history      # rewrite backend/data/usage_history.json

The engine (``backend/engine``) forecasts dinner demand per stock item from history records:

    {"ingredient_id", "unit", "start", "end", "daypart", "quantity",
     "source": "measured", "stockout": false, "complete": true}

This module invents ``PERIODS`` prior same-weekday dinners (17:00-20:00 America/New_York) before
``DEMO_EVALUATION_TIME``. Each dinner sells a noisy number of each dish variant in ``SALES_MIX``;
item usage = sum(sales x inventory requirements) with small portion noise, for every stocked item
(zeros recorded explicitly). The seed is fixed, so the file is reproducible.

The mix is tuned for the demo story: tofu is in high demand at dinner (tofu bowls, miso soup, swaps),
so promising tofu to a swap request eats into the dinner reserve; mushrooms are rarely used and are
surplus. Everything else stays comfortably covered by the synthetic stock.

All numbers are SYNTHETIC. The records say "measured" only because that is the engine's contract
for consumption history; nothing here was measured in a real kitchen. Deterministic, no LLM calls.
"""

from __future__ import annotations

import json
import random
import sys
from datetime import date, datetime, time, timedelta
from pathlib import Path
from typing import TYPE_CHECKING, Any
from zoneinfo import ZoneInfo

if TYPE_CHECKING:
    from .service import Inventory

DATA_DIR = Path(__file__).resolve().parents[1] / "data"
HISTORY_PATH = DATA_DIR / "usage_history.json"

# Fixed demo evaluation time (Saturday dinner service start). The synthetic history ends the
# Saturday before; use this as `now` for the demo so forecasts line up with the history.
DEMO_EVALUATION_TIME = datetime.fromisoformat("2026-11-07T17:00:00-05:00")
TIME_ZONE = "America/New_York"
DAYPART = "dinner"
DINNER_START = time(17, 0)
DINNER_HOURS = 3
PERIODS = 12
SEED = 20261107
SOURCE = "measured"

# (dish, ops, average sold per Saturday dinner) -- SYNTHETIC.
SALES_MIX: list[tuple[str, list[dict[str, Any]], float]] = [
    ("chicken_bowl", [], 3.5),
    ("chicken_bowl", [{"op": "add", "ingredient": "avocado"}], 0.8),
    ("chicken_bowl", [{"op": "substitute", "ingredient": "chicken", "with": "tofu"}], 0.8),
    ("chicken_bowl", [{"op": "substitute", "ingredient": "chicken", "with": "mushrooms"}], 0.3),
    ("tofu_bowl", [], 3.5),
    ("tofu_bowl", [{"op": "substitute", "ingredient": "tofu", "with": "mushrooms"}], 0.8),
    ("satay_noodles", [], 3.0),
    ("falafel_wrap", [], 4.0),
    ("miso_soup", [], 3.0),
]
SALES_SPREAD = 0.15  # relative std-dev of dish sales between dinners ...
SALES_SPREAD_MIN = 0.4  # ... but at least this many dishes, so rare variants still vary
PORTION_SPREAD = 0.03  # relative std-dev of portioning per item and dinner


def dinner_window(day: date, tz: str = TIME_ZONE) -> tuple[datetime, datetime]:
    """[17:00, 20:00) local dinner window on ``day`` with the correct UTC offset (DST aware)."""
    start = datetime.combine(day, DINNER_START, tzinfo=ZoneInfo(tz))
    return start, start + timedelta(hours=DINNER_HOURS)


def generate_history(
    inv: "Inventory | None" = None,
    *,
    evaluation_time: datetime = DEMO_EVALUATION_TIME,
    periods: int = PERIODS,
    seed: int = SEED,
) -> dict[str, Any]:
    """Build the synthetic history document (records + how they were made)."""
    if inv is None:
        from .service import load_inventory
        inv = load_inventory()
    rng = random.Random(seed)
    items = inv.stocked_items()
    recipe = [(dish, ops, mean, inv.requirements(dish, ops)) for dish, ops, mean in SALES_MIX]
    local_day = evaluation_time.astimezone(ZoneInfo(TIME_ZONE)).date()
    records = []
    for k in range(periods, 0, -1):  # oldest first
        start, end = dinner_window(local_day - timedelta(days=7 * k))
        totals = {item: 0.0 for item in items}
        for _dish, _ops, mean, reqs in recipe:
            sold = max(0, round(rng.gauss(mean, max(SALES_SPREAD * mean, SALES_SPREAD_MIN))))
            for item, qty in reqs.items():
                totals[item] = totals.get(item, 0.0) + sold * qty
        for item in items:
            qty = totals[item] * max(0.0, rng.gauss(1.0, PORTION_SPREAD)) if totals[item] else 0.0
            records.append({
                "ingredient_id": item,
                "unit": inv.unit_of(item),
                "start": start.isoformat(),
                "end": end.isoformat(),
                "daypart": DAYPART,
                "quantity": round(qty),
                "source": SOURCE,
                "stockout": False,
                "complete": True,
            })
    return {
        "_note": ("SYNTHETIC usage history generated by `py -3 -m backend.inventory.history` from made-up "
                  "dish sales x catalog recipes (seeded noise). Not real restaurant data. 'measured' is the "
                  "engine's history contract label, not a claim of real measurement."),
        "evaluation_time": evaluation_time.isoformat(),
        "time_zone": TIME_ZONE,
        "daypart": DAYPART,
        "period_hours": DINNER_HOURS,
        "periods": periods,
        "seed": seed,
        "sales_mix": [{"dish": d, "ops": ops, "avg_per_dinner": m} for d, ops, m in SALES_MIX],
        "records": records,
    }


def load_usage_history_file(path: str | Path | None = None) -> dict[str, Any]:
    with open(Path(path) if path else HISTORY_PATH, encoding="utf-8") as f:
        return json.load(f)


def load_usage_history(path: str | Path | None = None) -> list[dict[str, Any]]:
    """History records in the engine's ``UsageRecord`` format."""
    return list(load_usage_history_file(path)["records"])


def render(doc: dict[str, Any]) -> str:
    """Pretty JSON with one history record per line (keeps the file small and diffable)."""
    head = {k: v for k, v in doc.items() if k != "records"}
    text = json.dumps(head, indent=2)[:-2]  # drop the closing "\n}"
    rows = ",\n".join("    " + json.dumps(r) for r in doc["records"])
    return f'{text},\n  "records": [\n{rows}\n  ]\n}}\n'


def main(argv: list[str]) -> None:
    HISTORY_PATH.write_text(render(generate_history()), encoding="utf-8")
    print(f"wrote {HISTORY_PATH}")


if __name__ == "__main__":
    main(sys.argv[1:])
