"""Walk through the demo scenarios on the sample data, or regenerate the shared allergy fixture.

    py -3 -m backend.inventory.demo             # print scenarios
    py -3 -m backend.inventory.demo --fixture   # rewrite fixtures/allergy_request_example.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from .service import load_inventory

FIXTURE = Path(__file__).resolve().parents[2] / "fixtures" / "allergy_request_example.json"


def allergy_example() -> dict:
    """Full example of an allergy request as it flows through parsing -> inventory -> forecast.
    The parser output and forecast/review parts are PROPOSED shapes for the team to agree on."""
    inv = load_inventory()
    parser_output = {
        "dish": "satay_noodles",
        "qty": 1,
        "original_text": "satay noodles but no peanuts at all, I have a severe peanut allergy",
        "ops": [
            {"op": "remove", "ingredient": "peanuts"},
            {"op": "substitute", "ingredient": "peanut_sauce", "with": None},
        ],
        "flags": {"level": "allergy", "allergens": ["peanut"], "severity": "severe",
                  "detected_by": ["llm", "keyword"]},
    }
    exclude = parser_output["flags"]["allergens"]
    first = inv.check("satay_noodles", parser_output["ops"], exclude_allergens=exclude)
    candidates = inv.substitute_candidates("satay_noodles", "peanut_sauce", exclude_allergens=exclude,
                                           base_ops=parser_output["ops"])
    chosen = candidates[0]
    return {
        "_note": "Generated by `py -3 -m backend.inventory.demo --fixture` from SYNTHETIC data. "
                 "parser_output, forecast_output and review are proposed shapes, not final.",
        "parser_output": parser_output,
        "inventory_check": first.to_dict(),
        "inventory_candidates": [c.to_dict() for c in candidates],
        "forecast_output_proposed": {
            "ranked": [{"with": c.with_, "rank": i + 1, "forecast_reason": "<from forecast>"}
                       for i, c in enumerate(candidates)],
        },
        "review_proposed": {
            "status": "needs_staff_review",
            "review_reasons": ["allergy: peanut"],
            "recommended": chosen.with_,
            "hold": {"order_id": "order-123", "requirements": chosen.requirements, "ttl_seconds": 600},
            "customer_message": "Proposed: Satay Noodles with Sesame dressing instead of peanut sauce, no "
                                "crushed peanuts. The kitchen is confirming your allergy request.",
            "staff_actions": ["approve", "edit", "reject"],
        },
    }


def main(argv: list[str]) -> None:
    if "--fixture" in argv:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(json.dumps(allergy_example(), indent=2) + "\n", encoding="utf-8")
        print(f"wrote {FIXTURE}")
        return

    inv = load_inventory()
    print("1) Close substitute:")
    r = inv.check("chicken_bowl", [{"op": "substitute", "ingredient": "chicken", "with": "tofu"}])
    print("  ", r.status, r.kitchen_instructions)

    print("2) Blocked by premade component:")
    r = inv.check("chicken_bowl", [{"op": "remove", "ingredient": "garlic"}])
    print("  ", r.status, r.reasons[0].message)

    print("3) Two feasible substitutes for forecast:")
    for c in inv.substitute_candidates("chicken_bowl", "chicken"):
        print(f"   {c.with_}: similarity {c.similarity} ({c.similarity_source}), "
              f"price {c.price_delta_cents:+}c, available {c.available}")

    print("4) Stock change before confirm:")
    ops = [{"op": "substitute", "ingredient": "chicken", "with": "tofu"}]
    r = inv.check("chicken_bowl", ops)
    inv.set_on_hand("tofu", 100, "dropped a tray")
    c = inv.confirm("order-9", r.requirements)
    print("  ", c.code, c.shortfalls, "-> re-check:", inv.check("chicken_bowl", ops).status)

    print("5) Allergy request (staff review):")
    ex = allergy_example()
    print("   first check:", ex["inventory_check"]["status"],
          [x["code"] for x in ex["inventory_check"]["reasons"]])
    print("   candidates:", [(c["with"], c["similarity"]) for c in ex["inventory_candidates"]])


if __name__ == "__main__":
    main(sys.argv[1:])
